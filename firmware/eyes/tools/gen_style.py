#!/usr/bin/env python3
"""Write firmware/eyes/eyes/style_default.h from firmware/eyes/style.json.

style.json is the single source of truth for how SOMA's eyes look; the
firmware and the host preview both compile the header this writes. Run it
after editing style.json (soma_driver/test/test_eyes_firmware.py fails if
the two disagree):

    python3 firmware/eyes/tools/gen_style.py
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
JSON = HERE / 'style.json'
HEADER = HERE / 'eyes' / 'style_default.h'
TOP = ('iris_r', 'pupil_r', 'gaze_reach', 'glint_dx', 'glint_dy', 'glint_r', 'lid_shadow')
COLORS = ('sclera', 'sclera_edge', 'iris_in', 'iris_out', 'pupil', 'lid', 'glint')
MOODS = ('neutral', 'happy', 'sad', 'angry', 'surprised', 'sleepy')
TIMING = ('blink_close', 'blink_open', 'saccade_min', 'saccade_max', 'blink_every_min',
          'blink_every_max', 'look_holds')


def rgb(hexcolor: str) -> str:
    if len(hexcolor) != 7 or hexcolor[0] != '#':
        raise ValueError(f'color {hexcolor!r} is not #rrggbb')
    v = int(hexcolor[1:], 16)
    return f'{{{v >> 16 & 255}, {v >> 8 & 255}, {v & 255}}}'


def render(style: dict) -> str:
    lines = ['// GENERATED by firmware/eyes/tools/gen_style.py from firmware/eyes/style.json.',
             '// Do not edit: edit style.json and run the script.',
             '#pragma once', '#include "style.h"', '', 'namespace eyes {', '',
             'inline Style default_style() {', '  Style s{};']
    lines += [f'  s.{k} = {float(style[k])!r}f;' for k in TOP]
    lines += [f'  s.{k} = Rgb{rgb(style["colors"][k])};' for k in COLORS]
    for i, m in enumerate(MOODS):
        d = style['moods'][m]
        lines.append(f'  s.moods[{i}] = {{{float(d["up"])!r}f, {float(d["tilt"])!r}f, '
                     f'{float(d.get("arch", 0))!r}f, {float(d["low"])!r}f, {float(d["curve"])!r}f}};  // {m}')
    lines += [f'  s.{k} = {float(style["timing_ms"][k])!r}f;' for k in TIMING]
    lines += ['  return s;', '}', '', '}  // namespace eyes', '']
    return '\n'.join(lines)


def main() -> int:
    text = render(json.loads(JSON.read_text()))
    if '--check' in sys.argv:
        return 0 if HEADER.exists() and HEADER.read_text() == text else 1
    HEADER.write_text(text)
    print(f'wrote {HEADER.relative_to(HERE.parents[1])}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
